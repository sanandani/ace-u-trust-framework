-- Oracle Database 23ai Free reference schema. Synthetic records only.
CREATE TABLE profiles (
  profile_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name VARCHAR2(100) NOT NULL,
  context_name VARCHAR2(40) NOT NULL,
  consent_flag CHAR(1) DEFAULT 'N' NOT NULL CHECK (consent_flag IN ('Y','N')),
  skills_json CLOB CHECK (skills_json IS JSON),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE artifacts (
  artifact_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id NUMBER NOT NULL REFERENCES profiles(profile_id),
  artifact_type VARCHAR2(40) NOT NULL,
  skills_json CLOB CHECK (skills_json IS JSON),
  embedding VECTOR(64, FLOAT32),
  authored_at TIMESTAMP
);
CREATE TABLE signals (
  signal_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id NUMBER NOT NULL REFERENCES profiles(profile_id),
  dimension CHAR(1) NOT NULL CHECK (dimension IN ('A','C','E','U')),
  signal_name VARCHAR2(80) NOT NULL,
  signal_value NUMBER(8,6),
  evidence_status VARCHAR2(12) CHECK (evidence_status IN ('verified','inferred','synthetic')),
  uncertainty NUMBER(8,6), context_name VARCHAR2(40) NOT NULL
);
CREATE TABLE scores (
  score_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id NUMBER NOT NULL REFERENCES profiles(profile_id),
  context_name VARCHAR2(40) NOT NULL,
  a_score NUMBER(8,6), c_score NUMBER(8,6), e_score NUMBER(8,6), u_score NUMBER(8,6),
  a_uncertainty NUMBER(8,6), c_uncertainty NUMBER(8,6), e_uncertainty NUMBER(8,6), u_uncertainty NUMBER(8,6),
  explanation CLOB, computed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE TABLE contest_log (
  contest_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id NUMBER NOT NULL REFERENCES profiles(profile_id),
  score_id NUMBER REFERENCES scores(score_id),
  signal_id NUMBER REFERENCES signals(signal_id),
  action VARCHAR2(20) NOT NULL CHECK (action IN ('contest','correct','override')),
  reason VARCHAR2(2000) NOT NULL,
  proposed_value NUMBER(8,6), status VARCHAR2(20) DEFAULT 'open' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  resolved_at TIMESTAMP
);
-- 23ai vector search can compute skill-vector distance; bounded uniqueness combines rarity and complementarity.
CREATE OR REPLACE FUNCTION skill_distance(p_left VECTOR, p_right VECTOR) RETURN NUMBER DETERMINISTIC IS
BEGIN RETURN VECTOR_DISTANCE(p_left, p_right, COSINE); END;
/
CREATE OR REPLACE FUNCTION bounded_uniqueness(p_rarity NUMBER, p_complementarity NUMBER,
  p_authenticity NUMBER, p_credibility NUMBER, p_empathy NUMBER, p_gate NUMBER DEFAULT 0.25)
RETURN NUMBER DETERMINISTIC IS
  l_trust NUMBER;
BEGIN
  l_trust := LEAST(p_authenticity, p_credibility, p_empathy);
  IF l_trust < p_gate THEN RETURN 0; END IF;
  RETURN LEAST(1, GREATEST(0, (p_rarity + p_complementarity) / 2 * l_trust));
END;
/
